# Find a dependency whose REST endpoint is not fixed by its reference type:
# DEP_PROBE_ENDPOINTS types, and ASM policies (addressed by ID, so looked up by fullPath)
# Returns: @{ Found; Type; Endpoint; Response }
function Resolve-DepObject {
    param([string]$Type, [string]$Path)
    
    if ($Type -eq "waf_policy") {
        $ep = "/mgmt/tm/asm/policies?`$filter=fullPath+eq+'$Path'&`$select=name,fullPath,enforcementMode"
        $r = Invoke-F5Get -Endpoint $ep

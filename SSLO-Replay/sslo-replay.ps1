# Send a REST request to the connected BIG-IP
# Returns: @{ Success; Response; StatusCode; Error; WebStatus }
function Invoke-F5Api {
    param(
        [string]$Method = "GET",
        [string]$Endpoint,
        [object]$Body = $null
    )
    
    $uri = "https://$($script:RemoteHost)$Endpoint"
    $headers = @{
        "Authorization" = "Basic $($script:AuthHeader)"
        "Content-Type" = "application/json"
    }
    
    $params = @{
        Uri = $uri
        Headers = $headers
        Method = $Method
        TimeoutSec = $script:API_TIMEOUT
        ErrorAction = "Stop"
    }
    
    if ($Body) {
        if ($Body -is [string]) {
            $params.Body = $Body
        } else {
            $params.Body = ($Body | ConvertTo-Json -Depth 20 -Compress)
        }
    }
    
    try {
        $response = Invoke-RestMethod @params
        return @{ Success = $true; Response = $response; StatusCode = 200 }
    } catch {
        $statusCode = 0
        # WebException.Status is a locale-invariant enum - unlike the exception
        # message, which .NET Framework localizes per Windows display language
        $webStatus = ""
        if ($_.Exception -is [System.Net.WebException]) {
            $webStatus = [string]$_.Exception.Status
        }
        if ($_.Exception.Response) {
            $statusCode = [int]$_.Exception.Response.StatusCode
        }
        return @{ Success = $false; Response = $null; StatusCode = $statusCode; Error = $_.Exception.Message; WebStatus = $webStatus }
    }
}

function Invoke-F5Get {
    param([string]$Endpoint)
    return Invoke-F5Api -Method "GET" -Endpoint $Endpoint
}

function Invoke-F5Post {
    param([string]$Endpoint, [object]$Body)
    return Invoke-F5Api -Method "POST" -Endpoint $Endpoint -Body $Body

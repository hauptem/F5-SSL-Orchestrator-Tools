        }
        return @{ Found = $false; Type = $Type; Endpoint = ""; Response = $null }
    }
    
    $objName = $Path -replace "^/Common/", ""
    foreach ($probe in $script:DEP_PROBE_ENDPOINTS[$Type]) {
        $ep = "$($probe.Endpoint)~Common~${objName}"
        $r = Invoke-F5Get -Endpoint $ep
        if ($r.Success) {
            $resolvedType = if ($probe.Type) { $probe.Type } else { $Type }
            return @{ Found = $true; Type = $resolvedType; Endpoint = $ep; Response = $r.Response }
        }
    }
    return @{ Found = $false; Type = $Type; Endpoint = ""; Response = $null }
}

# Extract all external dependency references from a single block's config data.
# Single implementation for record (dependency capture) and replay
# (prerequisite validation). Field paths follow the Ansible module
# ApiParameters classes, which parse these same state blocks
# Returns: array of @{ Type; Path; Endpoint [; ExpectedType] } records.
# Endpoint is "" for types resolved through Resolve-DepObject
function Get-BlockDependencyRefs {
    param(
        [string]$DeploymentType,
        [object]$ConfigData
    )
    
    # Function-local collection. Add-Ref reads it through dynamic scoping and
    # mutates it in place via .Add() - method calls do not create a local copy
    # the way assignment would
    $depRefs = [System.Collections.ArrayList]::new()
    
    # Add a reference if it is an external /Common/ path
    function Add-Ref {
        param([string]$Type, [string]$Path, [string]$Endpoint, [hashtable]$Extra = @{})
        if ([string]::IsNullOrWhiteSpace($Path)) { return }
        if ($Path -eq "none" -or $Path -eq "") { return }
        if (Test-IsSsloGenerated -ObjPath $Path) { return }
        if ($Path -notmatch "^/Common/") { return }
        if (Test-IsCertKeyEndpoint -Endpoint $Endpoint) { return }
        $rec = [ordered]@{ Type = $Type; Path = $Path; Endpoint = $Endpoint }
        foreach ($k in $Extra.Keys) { $rec[$k] = $Extra[$k] }
        [void]$depRefs.Add($rec)
    }
    
    switch ($DeploymentType) {
        
        "SSL_SETTINGS" {
            # Certificates and keys - name only, no content, no secrets
            # These bypass Add-Ref (which filters cert/key endpoints) to keep
            # name-only references in the manifest so the snapshot is self-documenting
            $certSeen = @{}
            foreach ($section in @("certKeyChain", "caCertKeyChain")) {
                if ($ConfigData.clientSettings -and $ConfigData.clientSettings.$section) {
                    foreach ($chain in $ConfigData.clientSettings.$section) {
                        # Certificate
                        if ($chain.cert -and $chain.cert -ne "" -and $chain.cert -match "^/Common/" -and -not $certSeen[$chain.cert]) {
                            $certSeen[$chain.cert] = $true
                            [void]$depRefs.Add([ordered]@{ Type = "certificate"; Path = $chain.cert; Endpoint = "/mgmt/tm/sys/crypto/cert/" })
                        }
                        # Key (may be same name as cert - tracked separately)
                        $keyPath = "key:$($chain.key)"
                        if ($chain.key -and $chain.key -ne "" -and $chain.key -match "^/Common/" -and -not $certSeen[$keyPath]) {
                            $certSeen[$keyPath] = $true
                            [void]$depRefs.Add([ordered]@{ Type = "key"; Path = $chain.key; Endpoint = "/mgmt/tm/sys/crypto/key/" })
                        }
                        # Chain cert (if different from cert)
                        if ($chain.chain -and $chain.chain -ne "" -and $chain.chain -match "^/Common/" -and -not $certSeen[$chain.chain]) {
                            $certSeen[$chain.chain] = $true
                            [void]$depRefs.Add([ordered]@{ Type = "certificate"; Path = $chain.chain; Endpoint = "/mgmt/tm/sys/crypto/cert/" })
                        }
                    }
                }
            }
            # Server CA bundle
            if ($ConfigData.serverSettings -and $ConfigData.serverSettings.caBundle) {
                $caBundle = $ConfigData.serverSettings.caBundle
                if ($caBundle -and $caBundle -ne "" -and $caBundle -match "^/Common/") {
                    [void]$depRefs.Add([ordered]@{ Type = "ca_bundle"; Path = $caBundle; Endpoint = "/mgmt/tm/sys/crypto/cert/" })
                }
            }
            # Cipher groups - client and server
            if ($ConfigData.clientSettings -and $ConfigData.clientSettings.ciphers) {
                Add-Ref "cipher_group" $ConfigData.clientSettings.ciphers.cipherGroup "/mgmt/tm/ltm/cipher/group/"
            }
            if ($ConfigData.serverSettings -and $ConfigData.serverSettings.ciphers) {
                Add-Ref "cipher_group" $ConfigData.serverSettings.ciphers.cipherGroup "/mgmt/tm/ltm/cipher/group/"
            }
            # Log publishers
            if ($ConfigData.clientSettings) {
                Add-Ref "log_publisher" $ConfigData.clientSettings.logPublisher "/mgmt/tm/sys/log-config/publisher/"
            }
            if ($ConfigData.serverSettings) {
                Add-Ref "log_publisher" $ConfigData.serverSettings.logPublisher "/mgmt/tm/sys/log-config/publisher/"
                # Server certificate validators: serverSettings.ocsp / serverSettings.crl
                Add-Ref "ocsp_validator" $ConfigData.serverSettings.ocsp "/mgmt/tm/sys/crypto/cert-validator/ocsp/"
                Add-Ref "crl_validator" $ConfigData.serverSettings.crl "/mgmt/tm/sys/crypto/cert-validator/crl/"
            }
        }
        
        "SERVICE" {
            # Services can be a single object or array
            $svcList = if ($ConfigData -is [System.Array]) { $ConfigData } else { @($ConfigData) }
            foreach ($svc in $svcList) {
                $cs = $svc.customService
                if (-not $cs) { continue }
                
                if ($cs.connectionInformation) {
                    $connInfo = $cs.connectionInformation
                    # VLANs - L3, HTTP, ICAP, off-box AWAF: connectionInformation.{from,to}BigipNetwork.vlan
                    foreach ($dir in @("fromBigipNetwork", "toBigipNetwork")) {
                        $vlan = $connInfo.$dir.vlan
                        # create=true: the gc processor builds the VLAN from the network block
                        if ($vlan -and $vlan.path -and $vlan.create -ne $true) {
                            Add-Ref "vlan" $vlan.path "/mgmt/tm/net/vlan/"
                        }
                    }
                    # VLANs - L2: connectionInformation.interfaces[].{fromBigipVlan,toBigipVlan}
                    foreach ($intf in @($connInfo.interfaces)) {
                        if (-not $intf) { continue }
                        foreach ($side in @("fromBigipVlan", "toBigipVlan")) {
                            $vlan = $intf.$side
                            if ($vlan -and $vlan.path -and $vlan.create -ne $true) {
                                Add-Ref "vlan" $vlan.path "/mgmt/tm/net/vlan/"
                            }
                        }
                    }
                }
                # VLANs - TAP: serviceSpecific.vlan.path
                if ($cs.serviceSpecific -and $cs.serviceSpecific.vlan -and $cs.serviceSpecific.vlan.path -and $cs.serviceSpecific.vlan.create -ne $true) {
                    Add-Ref "vlan" $cs.serviceSpecific.vlan.path "/mgmt/tm/net/vlan/"
                }
                # Monitor: loadBalancing.monitor.fromSystem (type probed at capture, not validated at replay)
                if ($cs.loadBalancing -and $cs.loadBalancing.monitor) {
                    $monPath = $cs.loadBalancing.monitor.fromSystem
                    if ($monPath -and $monPath -ne "" -and $monPath -notin $script:BUILTIN_MONITORS) {
                        [void]$depRefs.Add([ordered]@{ Type = "monitor"; Path = $monPath; Endpoint = "" })
                    }
                }
                # iRules: customService.iRuleList, customService.iRuleListEgress
                # (SSLO 13+), and serviceSpecific.iRuleList (on-box WAF)
                foreach ($ruleList in @($cs.iRuleList, $cs.iRuleListEgress, $cs.serviceSpecific.iRuleList)) {
                    foreach ($rule in @($ruleList)) {
                        Add-Ref "irule" (Get-RefName $rule) "/mgmt/tm/ltm/rule/"
                    }
                }
                # SNAT pool: customService.snatConfiguration.snat.referredObj
                if ($cs.snatConfiguration -and $cs.snatConfiguration.snat) {
                    Add-Ref "snatpool" $cs.snatConfiguration.snat.referredObj "/mgmt/tm/ltm/snatpool/"
                }
                # Service entry/return SSL profiles (client-ssl or server-ssl, probed)
                Add-Ref "ssl_profile" $cs.serviceEntrySSLProfile ""
                Add-Ref "ssl_profile" $cs.serviceReturnSSLProfile ""
                # Default persistence profile (SSLO 14+, type probed)
                Add-Ref "persistence_profile" $cs.defaultPersistenceProfile ""
                if ($cs.serviceSpecific) {
                    $ss = $cs.serviceSpecific
                    # Off-box AWAF HTTP profile
                    Add-Ref "profile_http" $ss.httpProfile "/mgmt/tm/ltm/profile/http/"
                    # On-box WAF: security policy and profiles
                    Add-Ref "waf_policy" $ss.appSecurityPolicy ""
                    Add-Ref "dos_profile" $ss.dosProtectionProfile "/mgmt/tm/security/dos/profile/"
                    Add-Ref "bot_defense_profile" $ss.botDefenseProfile "/mgmt/tm/security/bot-defense/profile/"
                    foreach ($lp in @($ss.logProfile)) {
                        Add-Ref "security_log_profile" (Get-RefName $lp) "/mgmt/tm/security/log/profile/"
                    }
                }
            }
        }
        
        "TOPOLOGY" {
            # Ingress VLANs: ingressNetwork.vlans[].name
            if ($ConfigData.ingressNetwork -and $ConfigData.ingressNetwork.vlans) {
                foreach ($vlan in $ConfigData.ingressNetwork.vlans) {
                    Add-Ref "vlan" (Get-RefName $vlan) "/mgmt/tm/net/vlan/"
                }
            }
            # SNAT pool: egressNetwork.snat.referredObj
            if ($ConfigData.egressNetwork -and $ConfigData.egressNetwork.snat) {
                Add-Ref "snatpool" $ConfigData.egressNetwork.snat.referredObj "/mgmt/tm/ltm/snatpool/"
            }
            # Gateway pool: egressNetwork.outboundGateways.referredObj
            # Field name per Ansible bigip_sslo_config_topology.py - 'gatewayPool' does not exist
            if ($ConfigData.egressNetwork -and $ConfigData.egressNetwork.outboundGateways) {
                Add-Ref "gateway_pool" $ConfigData.egressNetwork.outboundGateways.referredObj "/mgmt/tm/ltm/pool/"
            }
            # Application pool: pool (inbound topology, application mode)
            Add-Ref "ltm_pool" (Get-RefName $ConfigData.pool) "/mgmt/tm/ltm/pool/"
            # TCP profiles
            if ($ConfigData.tcpSettings) {
                Add-Ref "profile_tcp" $ConfigData.tcpSettings.clientTcpProfile "/mgmt/tm/ltm/profile/tcp/"
                Add-Ref "profile_tcp" $ConfigData.tcpSettings.serverTcpProfile "/mgmt/tm/ltm/profile/tcp/"
            }
            # HTTP profile: l7Profile
            Add-Ref "profile_http" $ConfigData.l7Profile "/mgmt/tm/ltm/profile/http/"
            # Custom iRules: iRulesList[].name or iRulesList[] as strings
            foreach ($rule in @($ConfigData.iRulesList)) {
                Add-Ref "irule" (Get-RefName $rule) "/mgmt/tm/ltm/rule/"
            }
            # LTM policies: cpmPolicies[]
            foreach ($pol in @($ConfigData.cpmPolicies)) {
                Add-Ref "ltm_policy" (Get-RefName $pol) "/mgmt/tm/ltm/policy/"
            }
            # Access profile (custom only - generated ones are filtered by Add-Ref)
            Add-Ref "access_profile" $ConfigData.accessProfile "/mgmt/tm/apm/profile/access/"
            # Log publisher: loggingConfig.logPublisher
            if ($ConfigData.loggingConfig) {
                Add-Ref "log_publisher" $ConfigData.loggingConfig.logPublisher "/mgmt/tm/sys/log-config/publisher/"
            }
            # DNS resolver: dnsResolver
            Add-Ref "dns_resolver" $ConfigData.dnsResolver "/mgmt/tm/net/dns-resolver/"
        }
        
        # SECURITY_POLICY: datagroups, VLANs, and URL categories in rule conditions
        # Field paths from bigip_sslo_config_policy.py condition handling
        "SECURITY_POLICY" {
            $allRules = @()
            if ($ConfigData.rules) { $allRules += $ConfigData.rules }
            
            foreach ($rule in $allRules) {
                foreach ($condition in $rule.conditions) {
                    if (-not $condition.options) { continue }
                    $opts = $condition.options
                    
                    # Datagroups in subnet match conditions: options.subnet[].subnet
                    # where valueType=datagroup. Internal type must be "ip"
                    foreach ($entry in @($opts.subnet)) {
                        if ($entry -and $entry.valueType -eq "datagroup") {
                            Add-Ref "datagroup" $entry.subnet "/mgmt/tm/ltm/data-group/internal/" @{ ExpectedType = "ip" }
                        }
                    }
                    
                    # Datagroups in port match conditions: options.port[].port where valueType=datagroup
                    foreach ($portEntry in @($opts.port)) {
                        if ($portEntry -and $portEntry.valueType -eq "datagroup") {
                            Add-Ref "datagroup" $portEntry.port "/mgmt/tm/ltm/data-group/internal/"
                        }
                    }
                    
                    # Datagroups in IP geolocation conditions: options.geolocations[].value where valueType=datagroup
                    foreach ($geoEntry in @($opts.geolocations)) {
                        if ($geoEntry -and $geoEntry.valueType -eq "datagroup") {
                            Add-Ref "datagroup" $geoEntry.value "/mgmt/tm/ltm/data-group/internal/"
                        }
                    }
                    
                    # Datagroups in match-pattern lists: options.value[] (server
                    # certificate DN/SAN, TLS ClientHello server name) and
                    # options.url[] (URL branching), entries {matchType, pattern,
                    # valueType} (bigip_sslo_config_policy.py _build_match_pattern_list)
                    foreach ($listKey in @("value", "url")) {
                        foreach ($patEntry in @($opts.$listKey)) {
                            if ($patEntry -and $patEntry.valueType -eq "datagroup") {
                                Add-Ref "datagroup" $patEntry.pattern "/mgmt/tm/ltm/data-group/internal/"
                            }
                        }
                    }
                    
                    # Client VLAN conditions: options.vlans[] holds VLAN paths and
                    # datagroup paths in one list - resolved by probing
                    foreach ($vlanEntry in @($opts.vlans)) {
                        Add-Ref "vlan_or_datagroup" (Get-RefName $vlanEntry) ""
                    }
                    
                    # URL categories in category lookup conditions: options.category[].
                    # IP reputation conditions reuse options.category for reputation
                    # categories (Spam Sources, BotNets, ...) and carry options.reputation;
                    # those are not URL categories
                    $isReputation = ([string]$condition.type -match "IP Reputation") -or ($opts.PSObject.Properties["reputation"])
                    if ($opts.category -and -not $isReputation) {
                        foreach ($catName in $opts.category) {
                            if ($catName -and $catName -ne "") {
                                [void]$depRefs.Add([ordered]@{ Type = "url_category"; Path = $catName; Endpoint = "/mgmt/tm/sys/url-db/url-category/" })
                            }
                        }
                    }
                }
            }
        }
    }
    
    return ,@($depRefs)
}

# Capture external object references from snapshot blocks
# Returns: @{ objects = array of dependency records }
function Invoke-DependencyCapture {
    param([array]$OutputBlocks)
    
    Write-LogStep "Recording dependencies..."
    
    $depMap = @{}  # Keyed by type:path for deduplication
    
    foreach ($entry in $OutputBlocks) {
        $dataPropertyId = $script:TYPE_PROPERTY_MAP[$entry.deploymentType]
        if (-not $dataPropertyId) { continue }
        
        $configData = $null
        foreach ($prop in $entry.block.inputProperties) {
            if ($prop.id -eq $dataPropertyId) {
                $configData = $prop.value
                break
            }
        }
        if ($null -eq $configData) { continue }
        
        $refs = Get-BlockDependencyRefs -DeploymentType $entry.deploymentType -ConfigData $configData
        if (-not $refs -or $refs.Count -eq 0) { continue }
        
        foreach ($ref in $refs) {
            $path = $ref.Path
            
            # Deduplicate - key by type:path so cert and key for same name don't collide
            $dedupKey = "$($ref.Type):${path}"
            if ($depMap.ContainsKey($dedupKey)) {
                if ($entry.deploymentName -notin $depMap[$dedupKey].referencedBy) {
                    $depMap[$dedupKey].referencedBy += $entry.deploymentName
                }
                continue
            }
            
            # Fetch from source - full config capture for recreatable types
            $dep = $null
            if ($ref.Type -in @("certificate", "key", "ca_bundle")) {
                # Cert/key/CA bundle - name only, no content, no secrets
                # Non-portable: these must be pre-installed on the target
                $dep = [ordered]@{
                    type       = $ref.Type
                    path       = $path
                    endpoint   = ""
                    portable   = $false
                    config     = $null
                }
            } elseif ($ref.Type -eq "url_category") {
                # Only capture custom URL categories - built-in always exist on any licensed BIG-IP
                # Built-in list from Ansible bigip_sslo_config_policy.py condition_category_list
                if (-not $script:BUILTIN_URL_CATEGORIES.ContainsKey($path)) {
                    $catEncoded = $path -replace " ", "%20"
                    $catResult = Invoke-F5Get -Endpoint "/mgmt/tm/sys/url-db/url-category/~Common~${catEncoded}"
                    $catConfig = $null
                    if ($catResult.Success) {
                        $catConfig = Remove-DepRuntimeFields -Config $catResult.Response
                    }
                    $dep = [ordered]@{
                        type       = "url_category"
                        path       = $path
                        endpoint   = "/mgmt/tm/sys/url-db/url-category/~Common~${catEncoded}"
                        portable   = $true
                        config     = $catConfig
                    }
                }
            } elseif ($ref.Type -eq "monitor") {
                # Monitor requires type probing to determine the correct endpoint
                $dep = Get-MonitorDependency -MonitorPath $path
                if ($dep -and $dep["config"]) {
                    $dep["config"] = Remove-DepRuntimeFields -Config $dep["config"]
                }
            } elseif ($script:DEP_PROBE_ENDPOINTS.ContainsKey($ref.Type) -or $ref.Type -eq "waf_policy") {
                # Endpoint depends on the object's subtype - probe. Recorded even
                # when not found on the source so the manifest names it
                $res = Resolve-DepObject -Type $ref.Type -Path $path
                $depConfig = $null
                if ($res.Found) { $depConfig = Remove-DepRuntimeFields -Config $res.Response }
                $dep = [ordered]@{
                    type       = $res.Type
                    path       = $path
                    endpoint   = $res.Endpoint
                    portable   = ($res.Type -in $script:PORTABLE_DEP_TYPES)
                    config     = $depConfig
                }
            } elseif ($ref.Type -eq "datagroup") {
                # Datagroups - full capture including records for accurate recreation
                $dgName = $path -replace "^/Common/", ""
                $dgResult = Invoke-F5Get -Endpoint "/mgmt/tm/ltm/data-group/internal/~Common~${dgName}"
                if ($dgResult.Success) {
                    $dep = [ordered]@{
                        type       = "datagroup"
                        path       = $path
                        endpoint   = "/mgmt/tm/ltm/data-group/internal/~Common~${dgName}"
                        portable   = $true
                        config     = Remove-DepRuntimeFields -Config $dgResult.Response
                    }
                }
            } else {
                # All other types - fetch full config for snapshot completeness
                $objName = $path -replace "^/Common/", ""
                $endpoint = $ref.Endpoint
                $fullEndpoint = "${endpoint}~Common~${objName}"
                $result = Invoke-F5Get -Endpoint $fullEndpoint
                if ($result.Success) {
                    $dep = [ordered]@{
                        type       = $ref.Type
                        path       = $path
                        endpoint   = $fullEndpoint
                        portable   = ($ref.Type -in $script:PORTABLE_DEP_TYPES)
                        config     = Remove-DepRuntimeFields -Config $result.Response
                    }
                }
            }
            
            if ($dep) {
                $dep["referencedBy"] = @($entry.deploymentName)
                $depMap[$dedupKey] = $dep
            }
        }
    }
    
    # Sort dependencies by type (infrastructure -> objects -> policy -> data) then by path
    $depSortOrder = @{
        "certificate"     = 1
        "key"             = 2
        "ca_bundle"       = 3
        "vlan"            = 4
        "monitor_tcp"           = 5
        "monitor_http"          = 6
        "monitor_https"         = 7
        "monitor_gateway_icmp"  = 8
        "monitor_icmp"          = 9
        "monitor_udp"           = 10
        "monitor_tcp_half_open" = 11
        "monitor_external"      = 12
        "monitor_unknown"       = 13
        "profile_tcp"           = 14
        "profile_http"          = 15
        "profile_client_ssl"    = 16
        "profile_server_ssl"    = 17
        "ssl_profile"           = 18
        "persistence_profile"   = 19
        "dos_profile"           = 20
        "bot_defense_profile"   = 21
        "security_log_profile"  = 22
        "cipher_rule"           = 23
        "cipher_group"          = 24
        "ocsp_validator"        = 25
        "crl_validator"         = 26
        "log_publisher"         = 27
        "snatpool"              = 28
        "gateway_pool"          = 29
        "ltm_pool"              = 30
        "dns_resolver"          = 31
        "irule"                 = 32
        "ltm_policy"            = 33
        "access_profile"        = 34
        "waf_policy"            = 35
        "datagroup"             = 36
        "vlan_or_datagroup"     = 37
        "url_category"          = 38
    }
    $depList = @($depMap.Values | Sort-Object { 
        $order = $depSortOrder[$_.type]
        if ($null -eq $order) { $order = 99 }
        $order
    }, { $_.path })
    
    if ($depList.Count -gt 0) {
        Write-LogOk "$($depList.Count) dependencies recorded"
    } else {
        Write-LogOk "No external dependencies found"
    }
    
    return [ordered]@{
        capturedAt = (Get-Date -Format "yyyy-MM-dd HH:mm:ss")
        objects    = $depList
    }
}

